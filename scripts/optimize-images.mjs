import sharp from 'sharp';
import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { basename, dirname, extname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_GAMES } from '../games.js';

// Reproducible asset build: originals are read-only. HTML updates are mechanical.
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pagePath = resolve(root, 'index.html');
let html = await readFile(pagePath, 'utf8');
const shots = [...html.matchAll(/<a class="gallery-item"[^>]*>/g)].map(([tag]) =>
    tag.match(/data-original="([^"]+)"/)?.[1] || tag.match(/href="([^"]+)"/)?.[1]);
if (shots.length !== 18 || shots.some(path => !path?.startsWith('images/slider/'))) throw new Error('Nieprawidłowa lista źródeł galerii.');
const manifest = {};
let before = 0;
let after = 0;
for (const [kind, sources] of [['covers', DEFAULT_GAMES.map(game => game.image)], ['gallery', shots]]) {
    for (const source of sources) {
        const sourcePath = resolve(root, source);
        const metadata = await sharp(sourcePath).metadata();
        const sourceBytes = (await stat(sourcePath)).size;
        const folder = `images/optimized/${kind}`;
        await mkdir(resolve(root, folder), { recursive: true });
        const stem = basename(source, extname(source));
        const widths = kind === 'gallery'
            ? [...new Set([640, 1280, 1920].map(width => Math.min(width, metadata.width)))]
            : [Math.min(640, metadata.width)];
        const sizes = [];
        for (const width of widths) {
            const target = `${folder}/${stem}-${width}.webp`;
            const pipeline = sharp(sourcePath).rotate().resize({ width, ...(kind === 'covers' ? { height: 960, fit: 'inside' } : {}), withoutEnlargement: true });
            const info = await pipeline.webp({ quality: kind === 'gallery' ? 80 : 82, effort: 5 }).toFile(resolve(root, target));
            sizes.push({ src: target, width: info.width, height: info.height, bytes: info.size });
        }
        const full = sizes.at(-1);
        manifest[source] = { src: full.src, width: full.width, height: full.height, sizes };
        before += sourceBytes;
        after += full.bytes;
        console.log(`${source}: ${Math.round(sourceBytes / 1024)} → ${Math.round(full.bytes / 1024)} KB`);
    }
}

html = html.replace(/<a class="gallery-item"[^>]*><img[^>]*>(<span>.*?<\/span>)<\/a>/g, (tag, caption) => {
    const source = tag.match(/data-original="([^"]+)"/)?.[1] || tag.match(/href="([^"]+)"/)?.[1];
    const asset = manifest[source];
    if (!asset) throw new Error(`Brak grafiki ${source}`);
    const label = tag.match(/aria-label="([^"]+)"/)[1].replace(/, (?:otwórz w nowej karcie|powiększ na stronie|view full size)$/, ', view full size').replace(/ — kadr (\d+)/, ' — screenshot $1');
    const alt = tag.match(/alt="([^"]+)"/)[1];
    const first = asset.sizes[0];
    const srcset = asset.sizes.map(size => `${size.src} ${size.width}w`).join(', ');
    return `<a class="gallery-item" href="${asset.src}" data-original="${source}" aria-label="${label}"><img src="${first.src}" srcset="${srcset}" sizes="(max-width: 650px) calc(86vw - 27.52px), (min-width: 2560px) 708px, (min-width: 1921px) calc(25vw + 68px), (min-width: 1168px) 552px, calc(50vw - 32px)" width="${first.width}" height="${first.height}" alt="${alt}" loading="lazy" decoding="async" draggable="false">${caption}</a>`;
});
await writeFile(pagePath, html);
await writeFile(resolve(root, 'image-assets.js'), `// Generated by npm run images:optimize. Do not edit by hand.\nexport const IMAGE_ASSETS = ${JSON.stringify(manifest, null, 2)};\n`);
console.log(`\nŹródła: ${(before / 1048576).toFixed(2)} MB; największe wersje WebP: ${(after / 1048576).toFixed(2)} MB; mniej o ${(100 - after / before * 100).toFixed(1)}%.`);
console.log('Podglądy srcset są mniejsze; pełny kadr pobierany jest dopiero przy powiększeniu. Oryginały zachowane.');
